#!/usr/bin/env python3
"""
Builds lib/generated/d1-bundle.ts for the protected /api/setup route (ADR 0002):
  - migrations/*.sql, one statement per line (D1 exec() runs newline-separated statements)
  - demo data: INSERTs dumped from the local D1 database after `pnpm db:seed`, parents before children
Usage: pnpm db:seed && python3 scripts/d1/build-bundle.py
"""
import glob, json, os, re, sqlite3, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

def statements(sql: str) -> list[str]:
    sql = "\n".join(l for l in sql.splitlines() if not l.strip().startswith("--"))
    out = []
    for stmt in re.split(r";\s*(?:\n|$)", sql):
        stmt = " ".join(stmt.split())
        if stmt:
            out.append(stmt + ";")
    return out

def local_db() -> str:
    files = [f for f in glob.glob(os.path.join(ROOT, ".wrangler/state/v3/d1/miniflare-D1DatabaseObject/*.sqlite")) if not f.endswith("metadata.sqlite")]
    if len(files) != 1:
        sys.exit(f"expected one local D1 database, found {len(files)} — run `pnpm db:migrate && pnpm db:seed`")
    return files[0]

def literal(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, bytes):
        return "X'" + v.hex() + "'"
    return "'" + str(v).replace("'", "''") + "'"

def table_order(con) -> list[str]:
    tables = [r[0] for r in con.execute("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' AND name NOT LIKE '_cf_%' AND name != 'd1_migrations'")]
    deps = {t: {r[2] for r in con.execute(f'PRAGMA foreign_key_list("{t}")') if r[2] != t} for t in tables}
    order, seen = [], set()
    def visit(t):
        if t in seen: return
        seen.add(t)
        for d in sorted(deps[t]): visit(d)
        order.append(t)
    for t in sorted(tables): visit(t)
    return order

def main():
    migrations = []
    for path in sorted(glob.glob(os.path.join(ROOT, "migrations/*.sql"))):
        migrations.append({"name": os.path.basename(path), "statements": statements(open(path).read())})

    con = sqlite3.connect(local_db())
    order = table_order(con)
    seed = []
    for t in order:
        cur = con.execute(f'SELECT * FROM "{t}"')
        cols = ", ".join(f'"{d[0]}"' for d in cur.description)
        for row in cur:
            seed.append(f'INSERT INTO "{t}" ({cols}) VALUES ({", ".join(literal(v) for v in row)});')
    wipe = [f'DELETE FROM "{t}";' for t in reversed(order)]
    # Sample dates are relative to the seed run; /api/setup shifts them to "now" when loading.
    date_cols = [[t, r[1]] for t in order for r in con.execute(f'PRAGMA table_info("{t}")') if r[2].upper() == "DATETIME"]
    built_at = con.execute("SELECT max(checked_at) FROM offer").fetchone()[0]

    out = os.path.join(ROOT, "lib/generated/d1-bundle.ts")
    with open(out, "w") as f:
        f.write("// Generated by scripts/d1/build-bundle.py — do not edit. Demo data is SAMPLE, not real availability.\n")
        f.write(f"export const MIGRATIONS: {{ name: string; statements: string[] }}[] = {json.dumps(migrations, ensure_ascii=False, indent=1)};\n\n")
        f.write(f"export const DEMO_WIPE: string[] = {json.dumps(wipe, ensure_ascii=False)};\n\n")
        f.write(f"export const DEMO_SEED: string[] = {json.dumps(seed, ensure_ascii=False, indent=0)};\n\n")
        f.write(f"/** Newest sample timestamp (latest offer check) — the shift anchor. */\nexport const DEMO_BUILT_AT = {json.dumps(built_at)};\n\n")
        f.write(f"export const DEMO_DATE_COLUMNS: [table: string, column: string][] = {json.dumps(date_cols)};\n")
    print(f"{len(migrations)} migrations, {len(seed)} seed rows across {len(order)} tables → {os.path.relpath(out, ROOT)} ({os.path.getsize(out)//1024} KB)")

main()
